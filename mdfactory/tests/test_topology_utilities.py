def test_sybyl_atom_types_positional():
    """Test _get_sybyl_atom_type positionally on small hand-built molecules."""
    from rdkit import Chem
    from rdkit.Chem import AllChem

    # Ethanol: CCO
    mol = Chem.AddHs(Chem.MolFromSmiles("CCO"))
    AllChem.EmbedMolecule(mol, AllChem.ETKDGv3())
    types = [_get_sybyl_atom_type(mol.GetAtomWithIdx(i)) for i in range(mol.GetNumAtoms())]
    assert types == ["C.3", "C.3", "O.3", "H", "H", "H", "H", "H", "H"]

    # Guanidine: N=C(N)N
    mol = Chem.AddHs(Chem.MolFromSmiles("N=C(N)N"))
    AllChem.EmbedMolecule(mol, AllChem.ETKDGv3())
    types = [_get_sybyl_atom_type(mol.GetAtomWithIdx(i)) for i in range(mol.GetNumAtoms())]
    assert types == ["N.pl3", "C.cat", "N.pl3", "N.pl3", "H", "H", "H", "H", "H"]

    # Acetate fragment: [O-]C=O — both oxygens should be O.co2
    mol = Chem.AddHs(Chem.MolFromSmiles("[O-]C=O"))
    AllChem.EmbedMolecule(mol, AllChem.ETKDGv3())
    types = [_get_sybyl_atom_type(mol.GetAtomWithIdx(i)) for i in range(mol.GetNumAtoms())]
    assert types[0] == "O.co2"  # charged oxygen
    assert types[2] == "O.co2"  # partner oxygen via resonance logic


def test_oco2_carboxylate_partner():
    """Test that both oxygens in a carboxylate get O.co2.

    The charged oxygen matches via formal charge, the neutral one via partner logic.
    """
    from rdkit import Chem
    from rdkit.Chem import AllChem

    mol = Chem.AddHs(Chem.MolFromSmiles("[O-]C=O"))
    AllChem.EmbedMolecule(mol, AllChem.ETKDGv3())

    # Atom 0: O with formal charge -1 → O.co2 directly
    o_charged = mol.GetAtomWithIdx(0)
    assert o_charged.GetFormalCharge() == -1
    assert _get_sybyl_atom_type(o_charged) == "O.co2"

    # Atom 2: neutral O bonded to C that also has O- → O.co2 via partner logic
    o_neutral = mol.GetAtomWithIdx(2)
    assert o_neutral.GetFormalCharge() == 0
    assert _get_sybyl_atom_type(o_neutral) == "O.co2"


ENTRY_TEXT = """\
; title
#define FLEXIBLE
[ Atoms ]
; nr type
1  CT  ; first
#ifdef X
2  CT
#endif

[ bonds ] ; trailing comment
1 2
"""


def test_iter_topology_entries_tracks_sections_and_keeps_comments():
    entries = list(iter_topology_entries(ENTRY_TEXT.splitlines(keepends=True)))
    # Blank, comment-only and preprocessor lines are not data; sections are lower-cased.
    assert [(e.section, e.code) for e in entries] == [
        ("atoms", "1  CT"),
        ("atoms", "2  CT"),
        ("bonds", "1 2"),
    ]
    assert entries[0].comment == "; first"
    assert entries[1].comment == ""
    # The index addresses the original line, so a caller can rewrite it.
    assert ENTRY_TEXT.splitlines()[entries[2].index] == "1 2"


def test_iter_topology_entries_headers_are_opt_in():
    lines = ENTRY_TEXT.splitlines()
    headers = [e for e in iter_topology_entries(lines, headers=True) if e.is_header]
    assert [(e.section, e.index) for e in headers] == [("atoms", 2), ("bonds", 9)]
    assert not any(e.is_header for e in iter_topology_entries(lines))


def test_iter_topology_entries_supports_early_stop():
    seen = []
    for entry in iter_topology_entries(ENTRY_TEXT.splitlines()):
        if entry.section != "atoms":
            break
        seen.append(entry.code)
    assert seen == ["1  CT", "2  CT"]



RENAME_ATOMTYPES = """\
; generated by Interchange
[ atomtypes ]
;name  at.num  mass  charge ptype sigma epsilon
LIG_0  6  12.011  0.0  A  0.34  0.45 ; carbon
LIG_1  8  15.999  0.0  A  0.30  0.88
"""

RENAME_ITP = """\
[ moleculetype ]
ABC 3

[ atoms ]
; nr type resnr residue atom cgnr charge mass
    1 LIG_0  1 LIG C   1 -0.10 12.011 ; first
    2 LIG_0  1 LIG C   2  0.15 12.011
    3 LIG_1  1 LIG O   3 -0.05 15.999 LIG_1 0.0 15.999

[ bonds ]
1 2 1 0.15 300000.0
"""


def _write_rename_inputs(tmp_path, itp=RENAME_ITP, atomtypes=RENAME_ATOMTYPES):
    itp_path, atomtypes_path = tmp_path / "mol.itp", tmp_path / "mol_atomtypes.itp"
    itp_path.write_text(itp)
    atomtypes_path.write_text(atomtypes)
    return itp_path, atomtypes_path


def _section_rows(path, section):
    rows, current = [], None
    for raw in path.read_text().splitlines():
        line = raw.split(";", 1)[0].strip()
        if line.startswith("["):
            current = line.strip("[] ")
        elif line and current == section:
            rows.append(line.split())
    return rows


def test_rename_atomtypes_renames_definitions_and_atom_columns(tmp_path):
    itp, atomtypes = _write_rename_inputs(tmp_path)

    mapping = rename_atomtypes(itp, atomtypes, "TABC123")

    assert mapping == {"LIG_0": "TABC123_0", "LIG_1": "TABC123_1"}
    assert [row[0] for row in _section_rows(atomtypes, "atomtypes")] == ["TABC123_0", "TABC123_1"]
    assert _section_rows(atomtypes, "atomtypes")[0][1:] == [
        "6",
        "12.011",
        "0.0",
        "A",
        "0.34",
        "0.45",
    ]
    atoms = _section_rows(itp, "atoms")
    assert [row[1] for row in atoms] == ["TABC123_0", "TABC123_0", "TABC123_1"]
    assert atoms[2][8] == "TABC123_1"  # B-state type column
    # Atom names, residue names, charges, masses and other sections are untouched.
    assert [row[4] for row in atoms] == ["C", "C", "O"]
    assert [row[3] for row in atoms] == ["LIG"] * 3
    assert [row[6:8] for row in atoms] == [
        ["-0.10", "12.011"],
        ["0.15", "12.011"],
        ["-0.05", "15.999"],
    ]
    assert _section_rows(itp, "bonds") == [["1", "2", "1", "0.15", "300000.0"]]
    assert "; first" in itp.read_text() and "; carbon" in atomtypes.read_text()
    assert "LIG_" not in itp.read_text() + atomtypes.read_text()


def test_rename_atomtypes_rejects_undefined_type(tmp_path):
    itp, atomtypes = _write_rename_inputs(tmp_path, itp=RENAME_ITP.replace("LIG_1  1", "LIG_7  1"))
    original = itp.read_text()
    with pytest.raises(ValueError, match="'LIG_7' used in .* is not defined"):
        rename_atomtypes(itp, atomtypes, "TABC123")
    # Nothing is written when the files do not match.
    assert itp.read_text() == original
    assert "LIG_0" in atomtypes.read_text()


